/* ---- 定向走线：每个结局一条路径，按“选项目标节点”指引 ---- */
function walk(projectData, targets) {
  const s = Engine.createSession(projectData);
  let i = 0;
  let guard = 0;
  while (s.status === 'playing' && guard < 300) {
    guard += 1;
    if (i >= targets.length) {
      return { ok: false, reason: '路径已用完仍在游戏中，当前节点 ' + s.nodeId };
    }
    const want = targets[i];
    const choices = s.choices;
    let hit = -1;
    if (want.charAt(0) === '#') {
      // 按选项文字关键字匹配（多个选项指向同一节点时用）
      const kw = want.slice(1);
      for (let k = 0; k < choices.length; k++) {
        if (choices[k].text.indexOf(kw) >= 0) { hit = k; break; }
      }
    } else {
      for (let k = 0; k < choices.length; k++) {
        if (choices[k].target === want) { hit = k; break; }
      }
    }
    if (hit >= 0) { s.choose(hit); i += 1; continue; }
    if (want === s.nodeId) { i += 1; continue; } // 自动跳转已经路过该节点
    return {
      ok: false,
      reason: '找不到指向 ' + want + ' 的可见选项（当前节点 ' + s.nodeId +
        '，可见：' + choices.map(function (c) { return c.text + '→' + c.target; }).join(' | ') + '）'
    };
  }
  if (guard >= 300) return { ok: false, reason: '步数超过 300' };
  return { ok: true, nodeId: s.nodeId };
}

